/// Robot wide settings from `robots/talos.h`.
pub mod talos {
    /// ROS namespace of every Talos node.
    pub const ROBOT_NAMESPACE: &str = "talos";

    /// Internal CAN bus: CAN FD, 1 Mbit/s arbitration and 5 Mbit/s data.
    pub const INTERNAL_CAN_RATE: u32 = 1_000_000;
    pub const INTERNAL_CAN_FD_RATE: u32 = 5_000_000;
    pub const INTERNAL_CAN_ID: u8 = canmore::client_ids::BUS_ID_INTERNAL;

    /// External CAN bus: classic CAN at 250 kbit/s.
    pub const EXTERNAL_CAN_RATE: u32 = 250_000;
    pub const EXTERNAL_CAN_ID: u8 = canmore::client_ids::BUS_ID_EXTERNAL;
}

