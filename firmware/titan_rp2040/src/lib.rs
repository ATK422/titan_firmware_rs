//! Shared embassy support for UWRT RP2040 boards, the Rust counterpart of the C `titan_*` and `driver_*` libraries.
//!
//! * [`safety`]: fault tracking, kill switches, watchdog and crash records (`titan_safety`)
//! * [`led`]: the RGB status LED (`driver_led`)
//! * [`mcp251xfd`] and [`canbus`]: the MCP2517FD CAN controller and the CANmore client on top of it
//!   (`driver_canbus`)
//! * [`link`]: the firmware side of `titan_link`, replacing the micro-ROS boilerplate in each board's `ros.c`
//! * [`board`]: one-call bring-up of all of the above for boards built on the `rp2040_can_block`
//! * [`drivers`]: device drivers shared by several boards
//! * [`can_block`]: pin assignments shared by every board built on the `rp2040_can_block`
//!
//! A board's `main` calls [`board::start`], then adds its own tasks. See `template` and `ivc_board` for examples.

#![no_std]

pub mod board;
pub mod canbus;
pub mod drivers;
pub mod led;
pub mod link;
pub mod mcp251xfd;
mod panic;
pub mod safety;

/// Pin assignments of the `rp2040_can_block` (`boards/mk2/blocks/rp2040_can_block.h`).
///
/// Embassy hands out pins as typed peripherals, so these are documentation for the board `main` functions, which
/// pass the matching `p.PIN_n` peripherals to [`led::StatusLed::new`] and the CAN setup.
pub mod can_block {
    /// Red status LED (also the fault LED, active low).
    pub const STATUS_LEDR_PIN: u8 = 13;
    /// Green status LED (active low).
    pub const STATUS_LEDG_PIN: u8 = 14;
    /// Blue status LED (active low).
    pub const STATUS_LEDB_PIN: u8 = 15;

    /// The MCP2517FD sits on SPI0.
    pub const MCP2517FD_NCS_PIN: u8 = 17;
    pub const MCP2517FD_SCK_PIN: u8 = 18;
    pub const MCP2517FD_MOSI_PIN: u8 = 19;
    pub const MCP2517FD_MISO_PIN: u8 = 20;
    /// 4 MHz reference clock generated by the RP2040 on GPOUT0.
    pub const MCP2517FD_CANCLK_PIN: u8 = 21;
    pub const MCP2517FD_INT_PIN: u8 = 22;

    /// UART0 TX used for debug output by the C firmware.
    pub const DEBUG_UART_TX_PIN: u8 = 16;
}

